// Prueba E2E de la interfaz (Playwright) contra el stack local.
// Uso: node dev/e2e.cjs  (requiere vite en :5173 y el stack local)
const { chromium, devices } = require('playwright')
const path = require('path')
const OUT = process.env.OUT || path.join(__dirname, 'shots')
require('fs').mkdirSync(OUT, { recursive: true })
const BASE = process.env.BASE || 'http://localhost:5173'
let fails = 0
const ok = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) fails++ }
const today = new Date(); const pad = (n) => String(n).padStart(2, '0')
const key = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
const plus = (n) => { const d = new Date(); d.setDate(d.getDate() + n); return key(d) }

;(async () => {
  const browser = await chromium.launch(BASE.startsWith('https') && process.env.HTTPS_PROXY ? { proxy: { server: process.env.HTTPS_PROXY } } : {})
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
  const page = await ctx.newPage()
  global.__page = page
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('console', (m) => m.type() === 'error' && !m.text().includes('realtime') && !m.text().includes('WebSocket') && !m.text().includes('fonts.g') && !m.text().includes('ERR_TUNNEL') && !m.text().includes('Failed to load resource') && errors.push(m.text()))

  // ---- Registro ----
  const email = `aracely${Date.now()}@test.dev`
  await page.goto(BASE + '/')
  await page.waitForURL('**/login')
  await page.getByText('Crear cuenta').last().click()
  await page.getByPlaceholder('Tu nombre').fill('Aracely')
  await page.getByPlaceholder('Correo').fill(email)
  await page.getByPlaceholder('Contraseña').fill('secreto123')
  await page.getByRole('button', { name: 'Crear cuenta' }).click()
  await page.waitForURL(BASE + '/')
  await page.getByText(/, Aracely/).waitFor()
  ok(true, 'registro y saludo personalizado')
  for (const n of ['Trabajo fijo', 'Odontóloga', 'Psicóloga', 'Courier', 'Personal']) ok(await page.locator('aside').getByText(n, { exact: true }).first().isVisible(), `sidebar: ${n}`)

  // ---- Captura rápida (tarea en segundos) ----
  const t0 = Date.now()
  await page.keyboard.press('c')
  await page.getByPlaceholder('Ej.: Editar reel de la odontóloga').fill('Editar reel limpieza dental')
  await page.getByRole('dialog').getByRole('button', { name: 'Odontóloga' }).click()
  await page.getByPlaceholder('Ej.: Editar reel de la odontóloga').press('Enter')
  await page.getByText('Tarea creada').last().waitFor()
  ok(Date.now() - t0 < 4000, `captura rápida de tarea en ${Date.now() - t0} ms`)

  // ---- Tarea completa con subtareas, prioridad y reunión ----
  await page.getByRole('button', { name: 'Nueva tarea' }).first().click()
  const dlg = page.getByRole('dialog')
  await dlg.getByPlaceholder('¿Qué tenés que hacer?').fill('Reunión de planificación diciembre')
  await dlg.getByRole('button', { name: 'Psicóloga' }).click()
  await dlg.getByRole('button', { name: 'Mañana' }).click()
  await dlg.locator('input[type=time]').fill('10:00')
  await dlg.locator('select').first().selectOption('urgent')
  await dlg.getByRole('button', { name: 'Es una reunión' }).click()
  await dlg.getByRole('button', { name: 'Prioridad del día' }).click()
  await dlg.getByText('Descripción, subtareas').click()
  await dlg.getByPlaceholder('Agregar subtarea…').fill('Llevar ideas')
  await dlg.getByPlaceholder('Agregar subtarea…').press('Enter')
  await dlg.getByPlaceholder('Agregar subtarea…').fill('Revisar métricas')
  await dlg.getByPlaceholder('Agregar subtarea…').press('Enter')
  await dlg.getByRole('button', { name: 'Guardar' }).click()
  await page.getByText('Tarea creada').last().waitFor()
  ok(await page.getByText('Reunión de planificación diciembre').first().isVisible(), 'tarea en Mis prioridades')

  // tarea vencida (ayer) para trabajo fijo
  await page.getByRole('button', { name: 'Nueva tarea' }).first().click()
  await dlg.getByPlaceholder('¿Qué tenés que hacer?').fill('Informe mensual atrasado')
  await dlg.getByRole('button', { name: 'Trabajo fijo' }).click()
  await dlg.locator('input[type=date]').fill(plus(-1))
  await dlg.locator('input[type=number]').fill('90')
  await dlg.getByRole('button', { name: 'Guardar' }).click()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${OUT}/01-dashboard.png` })

  // ---- Tabla de tareas: filtros, búsqueda, kanban ----
  await page.goto(BASE + '/tareas')
  await page.locator('div.uppercase:has-text("Vencidas")').first().waitFor()
  ok(await page.locator('text=Informe mensual atrasado').isVisible(), 'lista agrupa vencidas')
  await page.getByPlaceholder('Buscar tareas…').fill('reel')
  ok(await page.locator('text=Editar reel limpieza dental').isVisible() && !(await page.locator('text=Informe mensual atrasado').isVisible()), 'búsqueda filtra')
  await page.getByPlaceholder('Buscar tareas…').fill('')
  await page.locator('select[aria-label="Prioridad"]').selectOption('urgent')
  ok(await page.locator('text=Reunión de planificación diciembre').isVisible() && !(await page.locator('text=Editar reel limpieza dental').isVisible()), 'filtro prioridad')
  await page.locator('select[aria-label="Prioridad"]').selectOption('all')
  await page.locator('select[aria-label="Tipo de espacio"]').selectOption('fijo')
  ok(await page.locator('text=Informe mensual atrasado').isVisible() && !(await page.locator('text=Editar reel limpieza dental').isVisible()), 'filtro por tipo de espacio')
  await page.locator('select[aria-label="Tipo de espacio"]').selectOption('all')
  await page.getByRole('button', { name: 'Columnas' }).click()
  const card = page.locator('text=Editar reel limpieza dental').first()
  const target = page.locator('text=Soltá tareas acá').first()
  const cb = await card.boundingBox(), tb = await target.boundingBox()
  await page.mouse.move(cb.x + 20, cb.y + 5); await page.mouse.down()
  await page.mouse.move(cb.x + 40, cb.y + 20, { steps: 5 })
  await page.mouse.move(tb.x + tb.width / 2, tb.y + tb.height / 2, { steps: 15 }); await page.mouse.up()
  await page.waitForTimeout(800)
  await page.screenshot({ path: `${OUT}/02-kanban.png` })
  await page.getByRole('button', { name: 'Lista' }).click()
  ok(await page.locator('div[role=button]:has-text("Editar reel limpieza dental")').getByText('En proceso').isVisible(), 'kanban: tarea movida a En proceso (badge en lista)')
  // calendario
  await page.getByRole('button', { name: 'Calendario' }).click()
  await page.waitForTimeout(300)
  await page.screenshot({ path: `${OUT}/03-tareas-calendario.png` })

  // completar desde la lista
  await page.getByRole('button', { name: 'Lista' }).click()
  await page.locator('div[role=button]:has-text("Informe mensual atrasado") button[aria-label="Marcar como hecha"]').click()
  await page.waitForTimeout(500)
  ok(!(await page.locator('text=Informe mensual atrasado').isVisible()), 'completar tarea la oculta de "Abiertas"')

  // ---- Calendario editorial: pieza con imagen ----
  await page.goto(BASE + '/editorial')
  await page.getByRole('button', { name: 'Nueva pieza' }).click()
  await dlg.getByPlaceholder('Título o tema').fill('Mitos de la ansiedad')
  await dlg.getByRole('button', { name: 'Psicóloga' }).click()
  await dlg.getByRole('button', { name: 'Carrusel' }).click()
  await dlg.locator('input[type=date]').first().fill(plus(3))
  await dlg.locator('input[type=time]').first().fill('19:00')
  await dlg.getByPlaceholder('De qué trata').fill('5 mitos comunes sobre la ansiedad y qué dice la evidencia.')
  await dlg.locator('textarea').nth(1).fill('¿Sabías que la ansiedad no siempre es mala? 🧠')
  await dlg.locator('input[type=file]').setInputFiles(path.join(__dirname, '..', 'public', 'icon-512.png'))
  await dlg.locator('img').first().waitFor({ timeout: 10000 })
  ok(true, 'imagen subida al storage')
  await dlg.getByRole('button', { name: 'Guardar' }).click()
  await page.getByText('Pieza creada').last().waitFor()
  // segunda pieza reel
  await page.getByRole('button', { name: 'Nueva pieza' }).click()
  await dlg.getByPlaceholder('Título o tema').fill('Reel respiración 4-7-8')
  await dlg.getByRole('button', { name: 'Psicóloga' }).click()
  await dlg.getByRole('button', { name: 'Reel' }).click()
  await dlg.locator('input[type=date]').first().fill(plus(5))
  await dlg.getByRole('button', { name: 'Guardar' }).click()
  await page.getByText('Pieza creada').last().waitFor()
  await page.getByRole('button', { name: 'Lista' }).click()
  await page.screenshot({ path: `${OUT}/04-editorial-lista.png` })

  // ---- Plan del cliente: grilla + link ----
  await page.locator('aside').getByText('Psicóloga', { exact: true }).click()
  await page.getByRole('button', { name: 'Grilla' }).click()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${OUT}/05-plan-grilla.png` })
  const href = await page.getByRole('link', { name: 'Ver como cliente' }).getAttribute('href')
  ok(/\/c\/[0-9a-f]{36}$/.test(href), 'link de cliente: ' + href)
  // recordatorios programados
  await page.getByRole('button', { name: 'Próximos recordatorios' }).click()
  await page.waitForTimeout(300)
  const rem = await page.locator('text=Publicar carrusel: Mitos de la ansiedad').count()
  ok(rem === 3, `3 recordatorios programados para el carrusel (hay ${rem})`)
  await page.screenshot({ path: `${OUT}/06-recordatorios.png` })
  await page.keyboard.press('Escape'); await page.mouse.click(10, 10)

  // ---- Portal del cliente (otro navegador, sin sesión) ----
  const cctx = await browser.newContext({ ...devices['iPhone 13'] })
  const cp = await cctx.newPage()
  await cp.goto(href)
  await cp.getByText('Psicóloga').first().waitFor()
  await cp.waitForTimeout(500)
  await cp.screenshot({ path: `${OUT}/07-portal-cliente.png` })
  ok(await cp.locator('button[title="Mitos de la ansiedad"]').count() === 1, 'portal muestra la grilla')
  await cp.locator('button[title="Mitos de la ansiedad"]').click()
  await cp.getByRole('button', { name: 'Cambios' }).click()
  await cp.getByPlaceholder('Tu nombre').fill('Dra. Gómez')
  await cp.getByPlaceholder(/cambiar esta palabra/).fill('Cambiar "mitos" por "creencias"')
  await cp.getByRole('button', { name: 'Pedir cambios' }).click()
  await cp.getByText('Cambiar "mitos" por "creencias"').waitFor()
  await cp.screenshot({ path: `${OUT}/08-portal-comentario.png` })
  await cp.getByRole('button', { name: 'Cerrar' }).click()
  await cp.locator('button[title="Reel respiración 4-7-8"]').click()
  await cp.getByRole('button', { name: 'Aprobar' }).click()
  await cp.getByRole('button', { name: 'Aprobado' }).waitFor()
  ok(true, 'cliente pidió cambios y aprobó')

  // ---- La dueña ve el feedback ----
  await page.reload()
  await page.getByText('comentario(s) por resolver').waitFor()
  ok(true, 'panel muestra comentario del cliente')
  await page.getByRole('button', { name: 'Lista' }).click()
  ok(await page.locator('text=Pidió cambios').first().isVisible() && await page.locator('text=Aprobado por cliente').first().isVisible(), 'estados de aprobación actualizados')

  // ---- Persistencia + segundo dispositivo ----
  const ctx2 = await browser.newContext({ ...devices['Pixel 7'] })
  const m = await ctx2.newPage()
  await m.goto(BASE + '/login')
  await m.getByPlaceholder('Correo').fill(email)
  await m.getByPlaceholder('Contraseña').fill('secreto123')
  await m.getByRole('button', { name: 'Ingresar' }).click()
  await m.getByText(/, Aracely/).waitFor()
  await m.waitForTimeout(500)
  await m.screenshot({ path: `${OUT}/09-movil-panel.png`, fullPage: false })
  ok(await m.getByText('Reunión de planificación diciembre').first().isVisible(), 'otro dispositivo ve los mismos datos')
  await m.goto(BASE + '/semana')
  await m.waitForTimeout(500)
  await m.screenshot({ path: `${OUT}/10-movil-semana.png` })
  await m.goto(BASE + '/editorial')
  await m.waitForTimeout(500)
  await m.screenshot({ path: `${OUT}/11-movil-editorial.png` })
  await page.goto(BASE + '/tareas')
  await page.waitForTimeout(2500)
  await m.getByRole('button', { name: 'Captura rápida' }).first().click()
  await m.waitForTimeout(400)
  await m.screenshot({ path: `${OUT}/12-movil-captura.png` })
  await m.getByPlaceholder('Ej.: Editar reel de la odontóloga').fill('Comprar regalo cumple Romi')
  await m.getByRole('dialog').getByRole('button', { name: 'Personal' }).click()
  await m.getByRole('dialog').getByRole('button', { name: 'Crear' }).click()
  await m.getByText('Tarea creada').last().waitFor()
  const hasScroll = await m.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
  ok(!hasScroll, 'móvil sin scroll horizontal')
  // aparece en la compu en vivo, sin recargar
  ok(await page.getByText('Comprar regalo cumple Romi').waitFor({ timeout: 8000 }).then(() => true, () => false), 'sincronización en vivo: lo creado en el celular aparece en la compu sin recargar')

  // ---- Notas → tarea ----
  await page.goto(BASE + '/notas')
  await page.getByPlaceholder('Anotá una idea rápida y Enter…').fill('Idea: serie de reels "un día en el consultorio"')
  await page.keyboard.press('Enter')
  await page.getByText('Idea guardada').last().waitFor()
  await page.getByText('un día en el consultorio').click()
  await page.getByRole('button', { name: 'A tarea', exact: true }).click()
  await page.getByRole('dialog').getByText('Nueva tarea').waitFor()
  await page.getByRole('dialog').getByRole('button', { name: 'Guardar' }).click()
  await page.getByText('Tarea creada').last().waitFor()
  ok(true, 'nota convertida en tarea')

  // ---- Semana: mover tarea de día ----
  await page.goto(BASE + '/semana')
  await page.waitForTimeout(400)
  await page.screenshot({ path: `${OUT}/13-semana.png` })

  // ---- Eliminar + deshacer ----
  await page.goto(BASE + '/tareas')
  await page.getByText('Comprar regalo cumple Romi').click()
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '¿Seguro?' }).click()
  await page.getByText('Tarea eliminada').last().waitFor()
  ok(!(await page.getByText('Comprar regalo cumple Romi').isVisible()), 'tarea eliminada')
  await page.getByRole('button', { name: 'Deshacer' }).click()
  await page.getByText('Comprar regalo cumple Romi').waitFor()
  await page.waitForTimeout(800)
  await page.reload()
  ok(await page.getByText('Comprar regalo cumple Romi').waitFor({ timeout: 8000 }).then(() => true, () => false), 'deshacer restaura y persiste')

  // portal: token inválido
  await cp.goto(BASE + '/c/' + 'f'.repeat(36))
  ok(await cp.getByText('Enlace no disponible').waitFor({ timeout: 8000 }).then(() => true, () => false), 'portal con link inválido')

  // tema claro
  await page.goto(BASE + '/config')
  await page.getByRole('button', { name: 'Claro' }).click()
  await page.goto(BASE + '/')
  await page.waitForTimeout(400)
  await page.screenshot({ path: `${OUT}/14-claro.png` })
  await page.goto(BASE + '/config'); await page.getByRole('button', { name: 'Oscuro' }).click()

  ok(errors.length === 0, 'sin errores de consola: ' + errors.slice(0, 3).join(' | '))
  await browser.close()
  console.log(fails ? `\n${fails} fallas` : '\nTODO OK')
  process.exit(fails ? 1 : 0)
})().catch(async (e) => { console.error(e); try { await global.__page.screenshot({ path: `${OUT}/fallo.png` }) } catch {} process.exit(1) })
